"""Regenerate the vendor key shapes in `redact_shapes.yaml` from the gitleaks default rules.

`sentrook redact-shapes import --tag vX.Y.Z` fetches `config/gitleaks.toml` at that tag (or reads it
with `--from FILE`), keeps the rules that identify a vendor key by a fixed prefix, converts each into a
shape and rewrites the file. Entries with another `source` (kept by hand) are carried over unchanged.
The output depends only on the rules file, the tag and the hand-kept entries, so a re-run with the same
tag is a no-op.

A gitleaks rule becomes a shape like this:

- The secret is the rule's `secretGroup`, else its first capture group, else the whole regex. The
  keyword context and trailing delimiters around it are dropped, since the pass masks the value
  wherever it appears.
- Go RE2 syntax is translated: POSIX classes are spelled out, `\\z` becomes `\\Z`, and a mid-pattern
  flag group such as `p8e-(?i)[a-z0-9]{32}` (RE2 applies it to the rest of the enclosing group) becomes
  a scoped one, `p8e-(?i:[a-z0-9]{32})`.
- A trailing delimiter group (`(?:[^\\w-]|\\z)`) becomes a look-ahead, so the mask stops at the
  key.
- Unbounded repetition (`+`, `*`, `{n,}`) is capped at `REPEAT_CAP` characters, so each match does
  bounded work; a longer key still has its first `REPEAT_CAP` characters masked.
- Entropy thresholds and per-rule allowlists are not applied. With a fixed prefix in front, a
  low-entropy value is still masked; masking a value that is not a key costs little, missing one leaks
  it.

A rule is skipped, and listed under `skipped` in the file with the reason, when it is a generic shape
the pass keeps in code, its value is only a key next to its keyword (`NEEDS_CONTEXT`), its secret has
no fixed prefix of at least `MIN_PREFIX` characters in every alternative (keyword-assignment rules
such as `adafruit-api-key`, bare hex or digits), its variable part is shorter than `MIN_BODY`
characters (a constant marker, not a key), its shortest match is under `MIN_LENGTH` characters, it
nests variable repetition inside a long repeat, or it does not translate.
"""

