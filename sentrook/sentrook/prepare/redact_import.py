class Unsupported(ValueError):
    """A rule regex the importer cannot translate into a Python shape."""


# --------------------------------------------------------------------------- regex source surgery


@dataclass(frozen=True)
class _Group:
    open: int
    close: int
    #: `capture`, `noncapture`, `scoped` (`(?i:…)`), `inline` (`(?i)`) or `other` (look-arounds).
    kind: str
    flags: str = ""
    #: Offset of the group body from `open`.
    body: int = 1


def _class_end(src: str, i: int) -> int:
    """Index just past the character class that opens at `src[i] == "["`."""
    j = i + 1
    if j < len(src) and src[j] == "^":
        j += 1
    if j < len(src) and src[j] == "]":
        j += 1
    while j < len(src):
        if src[j] == "\\":
            j += 2
            continue
        if src[j] == "]":
            return j + 1
        j += 1
    raise Unsupported("unterminated character class")


_FLAGS = re.compile(r"\(\?([a-zA-Z-]+)([:)])")


def _groups(src: str) -> list[_Group]:
    """Every parenthesised group of `src`, in order of its opening parenthesis."""
    out: list[_Group | None] = []
    stack: list[tuple[int, int, str, str, int]] = []
    i = 0
    while i < len(src):
        c = src[i]
        if c == "\\":
            i += 2
            continue
        if c == "[":
            i = _class_end(src, i)
            continue
        if c == "(":
            flags_m = _FLAGS.match(src, i)
            if flags_m and flags_m.group(2) == ")":
                out.append(_Group(i, flags_m.end() - 1, "inline", flags_m.group(1)))
                i = flags_m.end()
                continue
            if src.startswith("(?P<", i) or (src.startswith("(?<", i) and src[i + 3] not in "=!"):
                kind, flags, body = "capture", "", src.index(">", i) + 1 - i
            elif src.startswith("(?:", i):
                kind, flags, body = "noncapture", "", 3
            elif flags_m:
                kind, flags, body = "scoped", flags_m.group(1), flags_m.end() - i
            elif src.startswith("(?", i):
                kind, flags, body = "other", "", 2
            else:
                kind, flags, body = "capture", "", 1
            out.append(None)
            stack.append((len(out) - 1, i, kind, flags, body))
        elif c == ")":
            if not stack:
                raise Unsupported("unbalanced parenthesis")
            slot, start, kind, flags, body = stack.pop()
            out[slot] = _Group(start, i, kind, flags, body)
        i += 1
    if stack:
        raise Unsupported("unbalanced parenthesis")
    return [g for g in out if g is not None]


def _scope_inline_flags(src: str) -> tuple[str, str]:
    """Strip a leading `(?flags)` (returned) and turn every later one into a scoped group that ends
    where RE2 ends it: at the close of the enclosing group, or at the end of the pattern."""
    lead = ""
    m = re.match(r"\(\?([a-zA-Z]+)\)", src)
    if m:
        lead, src = m.group(1), src[m.end() :]
    while True:
        groups = _groups(src)
        inline = next((g for g in groups if g.kind == "inline"), None)
        if inline is None:
            return src, lead
        enclosing = [g for g in groups if g.kind != "inline" and g.open < inline.open < g.close]
        end = min((g.close for g in enclosing), default=len(src))
        src = (
            src[: inline.open]
            + f"(?{inline.flags}:"
            + src[inline.close + 1 : end]
            + ")"
            + src[end:]
        )


def _extract(src: str, secret_group: int, lead: str) -> str:
    """The secret part of a rule regex, with the flags in effect around it made explicit."""
    groups = _groups(src)
    captures = [g for g in groups if g.kind == "capture"]
    index = secret_group or (1 if captures else 0)
    if index == 0:
        secret, enclosing = src, []
    else:
        if index > len(captures):
            raise Unsupported(f"no capture group {index}")
        group = captures[index - 1]
        secret = src[group.open + group.body : group.close]
        enclosing = [g for g in groups if g.kind == "scoped" and g.open < group.open < g.close]
    for g in sorted(enclosing, key=lambda g: -g.open):
        secret = f"(?{g.flags}:{secret})"
    if lead:
        secret = f"(?{lead}:{secret})"
    return secret


def _lookahead_delimiter(src: str) -> str:
    """A trailing delimiter group such as `(?:[^\\w-]|\\Z)` becomes a look-ahead, so the mask does not
    take the quote, comma or newline after the key."""
    last = max(_groups(src), key=lambda g: g.close, default=None)
    if last is None or last.close != len(src) - 1 or last.kind != "noncapture":
        return src
    body = src[last.open + last.body : last.close]
    if not re.search(r"\|(?:\\Z|\$)$", body):
        return src
    return src[: last.open] + "(?=" + body + ")"


_OPEN_REPEAT = re.compile(r"\{(\d+),\}")


def _cap_repeats(src: str, cap: int) -> str:
    """Bound every unbounded repetition at `cap`."""
    out: list[str] = []
    i = 0
    while i < len(src):
        c = src[i]
        if c == "\\":
            out.append(src[i : i + 2])
            i += 2
        elif c == "[":
            end = _class_end(src, i)
            out.append(src[i:end])
            i = end
        elif c in "+*":
            out.append(f"{{{1 if c == '+' else 0},{cap}}}")
            i += 1
        elif c == "{" and (m := _OPEN_REPEAT.match(src, i)):
            out.append(f"{{{m.group(1)},{cap}}}")
            i = m.end()
        else:
            out.append(c)
            i += 1
    return "".join(out)


def translate(rule: dict[str, Any]) -> str:
    """The Python regex for a gitleaks rule's secret (no boundary in front)."""
    src = str(rule["regex"])
    for posix, expansion in _POSIX_CLASSES.items():
        src = src.replace(posix, expansion)
    if "[:" in src and ":]" in src:
        raise Unsupported("unknown POSIX class")
    src = src.replace(r"\z", r"\Z")
    src, lead = _scope_inline_flags(src)
    secret = _extract(src, int(rule.get("secretGroup") or 0), lead)
    secret = _lookahead_delimiter(secret)
    secret = _cap_repeats(secret, REPEAT_CAP)
    try:
        re.compile(secret)
    except re.error as exc:
        raise Unsupported(f"does not compile: {exc}") from exc
    return secret


# --------------------------------------------------------------------------- analysis


def _fixed_choice(items: Any) -> bool:
    """A character class of at most four literal characters (`[pousr]` is not, `[us]` is): Python's
    parser folds `ghu|ghs` into `gh[us]`, which is still a fixed prefix."""
    return len(items) <= 4 and all(str(op) == "LITERAL" for op, _ in items)


def _literal_prefix(items: Any) -> tuple[int, bool]:
    """Length of the literal run every match of `items` starts with, and whether `items` is entirely
    literal (so the run continues past it)."""
    n = 0
    for op, av in items:
        name = str(op)
        if name == "LITERAL" or (name == "IN" and _fixed_choice(av)):
            n += 1
        elif name == "AT":
            continue
        elif name == "SUBPATTERN":
            k, whole = _literal_prefix(av[-1])
            n += k
            if not whole:
                return n, False
        elif name == "BRANCH":
            alts = [_literal_prefix(alt) for alt in av[1]]
            n += min(k for k, _ in alts)
            if not all(whole for _, whole in alts):
                return n, False
        else:
            return n, False
    return n, True


def literal_prefix(regex: str) -> int:
    return _literal_prefix(sre_parse.parse(regex))[0]


def min_length(regex: str) -> int:
    return int(sre_parse.parse(regex).getwidth()[0])


def _nested_repetition(items: Any, outer_max: int = 1) -> bool:
    for op, av in items:
        name = str(op)
        if name in ("MAX_REPEAT", "MIN_REPEAT"):
            lo, hi, sub = av
            if outer_max >= 16 and lo != hi:
                return True
            if _nested_repetition(sub, max(outer_max, hi)):
                return True
        elif name == "SUBPATTERN":
            if _nested_repetition(av[-1], outer_max):
                return True
        elif name == "BRANCH":
            if any(_nested_repetition(alt, outer_max) for alt in av[1]):
                return True
    return False


def nested_repetition(regex: str) -> bool:
    return _nested_repetition(sre_parse.parse(regex))


