def convert(rules_toml: str, tag: str) -> tuple[list[dict[str, Any]], dict[str, list[str]]]:
    """The shapes taken from a gitleaks rules file, sorted by rule id, and the skipped rule ids by
    reason."""
    rules = tomllib.loads(rules_toml).get("rules") or []
    shapes: list[dict[str, Any]] = []
    skipped: dict[str, list[str]] = {reason: [] for reason in SKIP_REASONS}
    for rule in sorted(rules, key=lambda r: str(r.get("id", ""))):
        rid = str(rule.get("id", ""))
        if rid in GENERIC:
            skipped["generic"].append(rid)
            continue
        if rid in NEEDS_CONTEXT:
            skipped["needs_context"].append(rid)
            continue
        if not rule.get("regex"):
            skipped["no_regex"].append(rid)
            continue
        try:
            regex = translate(rule)
            compile_shape(regex)
        except (Unsupported, re.error):
            skipped["unsupported"].append(rid)
            continue
        prefix, shortest = literal_prefix(regex), min_length(regex)
        if prefix < MIN_PREFIX:
            skipped["no_fixed_prefix"].append(rid)
        elif shortest - prefix < MIN_BODY:
            skipped["no_variable_body"].append(rid)
        elif shortest < MIN_LENGTH:
            skipped["too_short"].append(rid)
        elif nested_repetition(regex):
            skipped["nested_repetition"].append(rid)
        else:
            shapes.append(
                {
                    "name": rid,
                    "regex": regex,
                    "min_length": shortest,
                    "source": UPSTREAM_NAME,
                    "source_version": tag,
                }
            )
    return shapes, {k: v for k, v in skipped.items() if v}


def _q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render(
    version: Any, tag: str, shapes: list[dict[str, Any]], skipped: dict[str, list[str]]
) -> str:
    lines = [HEADER, f"version: {version}", ""]
    lines += [
        "upstream:",
        f"  name: {UPSTREAM_NAME}",
        f"  url: {UPSTREAM_URL}",
        f"  path: {UPSTREAM_PATH}",
        f"  tag: {tag}",
        "  license: MIT",
        "",
        "shapes:",
    ]
    for s in shapes:
        lines += [
            f"  - name: {s['name']}",
            f"    regex: {_q(str(s['regex']))}",
            f"    min_length: {s['min_length']}",
            f"    source: {s['source']}",
            f"    source_version: {s['source_version']}",
        ]
    lines += [
        "",
        "# Upstream rules not taken, by reason (see prepare/redact_import.py).",
        "skipped:",
    ]
    for reason, ids in skipped.items():
        lines.append(f"  {reason}:")
        lines += [f"    - {rid}" for rid in ids]
    return "\n".join(lines) + "\n"


@dataclass(frozen=True)
class Refresh:
    text: str
    changed: bool
    added: tuple[str, ...]
    removed: tuple[str, ...]
    modified: tuple[str, ...]


def refresh(path: Path, rules_toml: str, tag: str) -> Refresh:
    """The new contents of the shapes file at `path` for `tag`: hand-kept entries first, in their
    order, then the gitleaks shapes by rule id."""
    if not TAG_RE.fullmatch(tag):
        raise ValueError(f"not a release tag: {tag!r}")
    old_text = path.read_text(encoding="utf-8") if path.exists() else ""
    old = read_file(path) if path.exists() else {}
    old_shapes = [dict(s) for s in old.get("shapes") or ()]
    local = [s for s in old_shapes if s.get("source") != UPSTREAM_NAME]
    for s in local:
        s["min_length"] = min_length(str(s["regex"]))
    imported, skipped = convert(rules_toml, tag)
    taken = {s["name"] for s in local}
    imported = [s for s in imported if s["name"] not in taken]
    text = render(old.get("version", 1), tag, local + imported, skipped)
    before = {s["name"]: s["regex"] for s in old_shapes}
    after = {s["name"]: s["regex"] for s in local + imported}
    return Refresh(
        text=text,
        changed=text != old_text,
        added=tuple(sorted(set(after) - set(before))),
        removed=tuple(sorted(set(before) - set(after))),
        modified=tuple(sorted(n for n in set(before) & set(after) if before[n] != after[n])),
    )


def fetch(tag: str) -> str:
    """`config/gitleaks.toml` at `tag`."""
    import httpx

    if not TAG_RE.fullmatch(tag):
        raise ValueError(f"not a release tag: {tag!r}")
    response = httpx.get(RAW_URL.format(tag=tag), timeout=30.0, follow_redirects=True)
    response.raise_for_status()
    return response.text


