TAG_RE = re.compile(r"v\d+\.\d+\.\d+")

MIN_PREFIX = 3
MIN_BODY = 8
MIN_LENGTH = 16
REPEAT_CAP = 4096

#: Rules for shapes the pass keeps in code (`prepare.redact`), or that find a secret by its context
#: rather than its own form.
GENERIC: dict[str, str] = {
    "generic-api-key": "assignment forms are in code",
    "private-key": "PEM private keys are in code",
    "jwt": "JWTs are in code",
    "jwt-base64": "a generic token format, not a vendor key",
    "curl-auth-header": "the Authorization header is in code",
    "curl-auth-user": "found by its command-line context",
}

#: Keyword-assignment rules whose value has a prefix, but one too common to mask without the keyword
#: in front (`live_…` is also a snake_case name, `key-<hex>` a cache key).
NEEDS_CONTEXT: dict[str, str] = {
    "freemius-secret-key": "sk_ and any 29 non-space characters",
    "gocardless-api-token": "live_ and 40 word characters",
    "lob-api-key": "live_ or test_ and 35 hex digits",
    "mailgun-private-api-token": "key- and 32 hex digits",
}

SKIP_REASONS: tuple[str, ...] = (
    "generic",
    "needs_context",
    "no_regex",
    "no_fixed_prefix",
    "no_variable_body",
    "too_short",
    "nested_repetition",
    "unsupported",
)

_POSIX_CLASSES = {
    "[:alnum:]": "A-Za-z0-9",
    "[:alpha:]": "A-Za-z",
    "[:digit:]": "0-9",
    "[:xdigit:]": "0-9A-Fa-f",
    "[:upper:]": "A-Z",
    "[:lower:]": "a-z",
    "[:space:]": r"\s",
    "[:word:]": r"\w",
    "[:punct:]": r"!-/:-@\[-`{-~",
}

