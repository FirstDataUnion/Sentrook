# ---- the scanner accepts what is sent --------------------------------------------------------------------


def test_host_turn_requests_pass_the_scanners_validation(h):
    planir = pytest.importorskip("sentrook.planir.models")
    validate = pytest.importorskip("sentrook.planir.validate")
    turn(h, "t1", "ask a helper to check the mirror and build it")
    call(h, "t1", "c1")
    result(h, "t1", "c1")
    turn(h, "t2", NOTICE)
    turn(h, "t3", PROCESS)
    call(h, "t3", "c2")
    turn(h, "t4", "[Heartbeat — recurring instruction, fires every 1h]\nCheck the queue.")
    call(h, "t4", "c3")
    for raw in h.scans:
        validate.check(planir.PlanIR.model_validate(raw), raw.get("scan_kind"))
    assert [i["kind"] for i in h.scans[1]["new_inputs"]] == [
        "tool_result",
        "subagent_reply",
        "other",
    ]
