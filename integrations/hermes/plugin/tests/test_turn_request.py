"""The request, trigger and sender a call carries on the owner's turns and on the turns Hermes starts itself.

Every tool call of a turn that began with the owner's message carries that message, trigger `message` and
the owner as sender, however many model calls the turn's tool loop makes (a synchronous `delegate_task`
included). Hermes also starts turns with its own text: a finished asynchronous sub-agent, a background
process's result, a kanban event (event notices), or a heartbeat, `/loop` wakeup or goal step (standing
instructions). None of them is the owner speaking: when the sender reads as the owner the turn becomes
`system` (or `heartbeat`) with an unknown sender. An event notice's text goes as an untrusted input and the
request stays the session's last one (with `carried_from_turn`). Any other sender who types these forms
keeps their trigger and sender, and never gets an earlier request in place of their own text.
"""

